"""Run all predeclared checks together; preserve canonical scores separately."""
import argparse
import json
import shutil
import subprocess
from pathlib import Path

ROOT=Path('/home/user')
OUT=ROOT/'redteam/final_hardening/results'
REGISTRY=ROOT/'scripts/samplers'


def command(*args):
    subprocess.run(args,cwd=ROOT,check=True)


def registry(producers):
    for p in REGISTRY.glob('*.sh'):p.unlink()
    for name,producer in producers.items():
        (REGISTRY/f'{name}.sh').write_text('#!/bin/bash\nset -euo pipefail\ncd /home/user\n'+producer+' --problem "$1" --output-dir "$2"\n')


def restore_registry(saved):
    for p in REGISTRY.glob('*.sh'):p.unlink()
    for name,content in saved.items():(REGISTRY/name).write_text(content)


def freeze_reference():
    # Preserve every published number; replace only gym-scale measurements.
    path=ROOT/'scoring/reference.json';reference=json.loads(path.read_text())
    canonical=json.loads((OUT/'canonical_test.json').read_text())
    if any('sgdd' in e.get('_failures',{}) for e in canonical['experiments'].values()):
        raise RuntimeError('Reference failed hidden inference; do not freeze or audit against a failed reference')
    for exp,e in reference['experiments'].items():
        for name,row in canonical['experiments'][exp]['results'].items():
            e['results'][name]={'type':'proposed' if name=='sgdd' else 'baseline',**row}
    reference['_note']=reference['_note'].replace('Gym-scale results will be regenerated by the bundled job.','Gym-scale results are the canonical final serialized hidden-test run; public training scores remain separate.')
    path.write_text(json.dumps(reference,indent=2)+'\n')


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--rescore-train',action='store_true',
                        help='Reuse complete raw training outputs when only hidden evaluation changed')
    parser.add_argument('--resume-test',action='store_true',
                        help='After node loss, rescore matching raw outputs and run missing hidden work')
    args=parser.parse_args()
    OUT.mkdir(parents=True,exist_ok=True)
    backup=OUT/'canonical_registry.json'
    if args.resume_test and backup.exists():
        saved=json.loads(backup.read_text())
        restore_registry(saved)
    else:
        saved={p.name:p.read_text() for p in REGISTRY.glob('*.sh')}
        backup.write_text(json.dumps(saved,indent=2)+'\n')
    hidden_args=['--resume'] if args.resume_test else []
    # Runs are deliberately serialized. No audit process computes beside these.
    command('bash','scripts/evaluate_train.sh',*(['--rescore'] if args.rescore_train else []))
    shutil.copyfile('eval/train/results/points.json',OUT/'train_points.json')
    shutil.copyfile('scoring/scores_train.json',OUT/'canonical_train.json')
    shutil.copyfile('scoring/scores_train.json','scoring/scores.json')
    command('bash','scripts/evaluate_test.sh',*hidden_args)
    shutil.copyfile('eval/test/results/points.json',OUT/'test_points.json')
    shutil.copyfile('scoring/scores_test.json',OUT/'canonical_test.json')
    freeze_reference()
    variants={k:f'python -m redteam.final_hardening.improvements {k}' for k in ['longer','seed1','weaker']}
    shortcuts=['copy_reference','rule','template','negative','two_latents','extra','empty','float','nan','old_exact','forged','tamper_problem','constant']
    variants.update({f'shortcut_{k}':f'python -m redteam.final_hardening.variants {k}' for k in shortcuts})
    # Normal runs exercise the no-argument entrypoint. Recovery explicitly reuses
    # raw arrays, never a saved score, and does not change default evaluation.
    try:
        registry(variants)
        command('bash','scripts/evaluate_test.sh',*hidden_args)
        shutil.copyfile('eval/test/results/points.json',OUT/'audit_points.json')
        shutil.copyfile('scoring/scores_test.json',OUT/'audit_test.json')
        command('python','-m','redteam.final_hardening.report')
        summary=json.loads((OUT/'summary.json').read_text())
        # Predeclared accuracy fallback: run only if the first improvement does
        # not clear its paired interval and the independent-seed noise check.
        if not summary['better_than_noise']:
            registry({'longer_accurate':'python -m redteam.final_hardening.improvements longer_accurate'})
            command('bash','scripts/evaluate_test.sh',*hidden_args)
            for source,target in [('eval/test/results/points.json','audit_points.json'),('scoring/scores_test.json','audit_test.json')]:
                existing=json.loads((OUT/target).read_text());extra=json.loads(Path(source).read_text())
                for exp,entry in extra['experiments'].items():
                    if 'results' in entry:
                        existing['experiments'][exp]['results'].update(entry['results'])
                        if '_failures' in entry:existing['experiments'][exp].setdefault('_failures',{}).update(entry['_failures'])
                    else:existing['experiments'][exp].update(entry)
                (OUT/target).write_text(json.dumps(existing,indent=2)+'\n')
            command('python','-m','redteam.final_hardening.report')
    finally:
        restore_registry(saved)
        shutil.copyfile(OUT/'canonical_train.json','scoring/scores_train.json')
        shutil.copyfile(OUT/'canonical_train.json','scoring/scores.json')
        shutil.copyfile(OUT/'canonical_test.json','scoring/scores_test.json')

if __name__=='__main__':main()
